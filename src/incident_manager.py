"""
ServiceNow Incident & ITIL Escalation Routing Engine for FinOps-BatchGuard.
Triage batch failures, upstream cascading blocks, and SLA breaches into
structured ServiceNow Incident tickets (INC0010xxx) with automated routing.
"""

import os
import json
import logging
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from src import database

DEFAULT_MATRIX_PATH = Path(__file__).resolve().parent.parent / "config" / "escalation_matrix.json"
OUTBOX_DIR = Path(__file__).resolve().parent.parent / "data" / "servicenow_outbox"


class IncidentManager:
    def __init__(
        self,
        matrix_path: Optional[Path] = None,
        db_path: Optional[Path] = None,
        outbox_dir: Optional[Path] = None,
        logger: Optional[logging.Logger] = None,
    ) -> None:
        self.matrix_path = matrix_path or DEFAULT_MATRIX_PATH
        self.db_path = db_path or database.DEFAULT_DB_PATH
        self.outbox_dir = outbox_dir or OUTBOX_DIR
        self.logger = logger or logging.getLogger("batch_engine.incident_mgr")
        self.matrix_config: Dict[str, Any] = {}
        self.load_escalation_matrix()

    def load_escalation_matrix(self) -> None:
        if not self.matrix_path.exists():
            raise FileNotFoundError(f"Escalation matrix config not found at: {self.matrix_path}")
        with open(self.matrix_path, "r", encoding="utf-8") as f:
            self.matrix_config = json.load(f)

    def _get_routing(self, job_id: str) -> Dict[str, Any]:
        rules = self.matrix_config.get("job_escalation_rules", {})
        return rules.get(
            job_id,
            {
                "assignment_group": "Batch-Operations-L1",
                "sme_contact": "Enterprise Command Center",
                "category": "Batch Operations",
                "subcategory": "General Batch Incident",
                "runbook_id": "KB0010001",
                "business_service": "Core Banking Processing",
            },
        )

    def triage_and_escalate(self, run_id: str) -> List[Dict[str, Any]]:
        """
        Evaluates all jobs in the given run_id from the database and generates
        appropriate ServiceNow Incident tickets based on ITIL triage rules:
          - Rule A: Hard Failure -> P1 Critical Incident (DBA/Core Support + Runbook)
          - Rule B: Cascading Block -> Linked Child Ticket (State: On Hold - Awaiting Upstream)
          - Rule C: Recovered Job with SLA Breach -> P2 High SLA Warning Ticket
        """
        self.outbox_dir.mkdir(parents=True, exist_ok=True)
        job_runs = database.get_job_runs(run_id=run_id, db_path=self.db_path)
        if not job_runs:
            self.logger.warning(f"No job_runs found for run_id={run_id} to triage.")
            return []

        # Sort so that hard failures (parents) are processed before blocked downstream jobs
        def sort_priority(r: Dict[str, Any]) -> int:
            if r["status"] == "FAILED":
                return 0
            if r["sla_breached"] and r["status"] == "SUCCESS":
                return 1
            if r["status"] == "BLOCKED_BY_UPSTREAM":
                return 2
            return 3

        sorted_runs = sorted(job_runs, key=sort_priority)

        created_incidents: List[Dict[str, Any]] = []
        # Maps failed job_id -> generated parent incident_number
        parent_incident_map: Dict[str, str] = {}

        now_ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        for job in sorted_runs:
            job_id = job["job_id"]
            job_name = job["job_name"]
            status = job["status"]
            exit_code = job.get("exit_code")
            attempt_count = job.get("attempt_count", 0)
            duration_sec = job.get("duration_sec", 0.0)
            sla_breached = bool(job.get("sla_breached", 0))
            stderr_log = job.get("stderr_log", "")

            routing = self._get_routing(job_id)
            assignment_group = routing["assignment_group"]
            sme_contact = routing["sme_contact"]
            runbook_id = routing.get("runbook_id", "KB0010001")
            category = routing.get("category", "Batch Operations")
            subcategory = routing.get("subcategory", "General")

            # ------------------------------------------------------------------
            # Rule A: Hard Failure -> P1 Critical Incident
            # ------------------------------------------------------------------
            if status == "FAILED":
                inc_num = database.get_next_incident_number(self.db_path)
                parent_incident_map[job_id] = inc_num

                short_desc = f"[P1 INCIDENT] Hard Failure in {job_name} ({job_id}) - Exit Code {exit_code}"
                
                work_notes = (
                    f"--- INCIDENT AUTO-GENERATED BY FINOPS-BATCHGUARD ---\n"
                    f"Run ID: {run_id}\n"
                    f"Job: {job_id} ({job_name})\n"
                    f"Criticality: P1 | Exit Code: {exit_code} | Total Attempts: {attempt_count}\n"
                    f"Diagnostic stderr:\n{stderr_log.strip()}\n\n"
                    f"ACTION REQUIRED: P1 Major Incident Bridge required.\n"
                    f"Assigned Group: {assignment_group} | Primary SME: {sme_contact}\n"
                    f"Standard Operating Procedure / Runbook: {runbook_id}"
                )

                description = (
                    f"Critical banking batch job '{job_id}' encountered an unrecoverable failure "
                    f"after {attempt_count} attempts with exit code {exit_code}.\n"
                    f"All auto-retries exhausted. Downstream settlement and statutory reporting are compromised.\n"
                    f"Refer to Runbook {runbook_id} for immediate remediation steps."
                )

                inc_record = {
                    "incident_number": inc_num,
                    "run_id": run_id,
                    "job_id": job_id,
                    "incident_type": "HARD_FAILURE",
                    "priority": "P1 - Critical",
                    "state": "Assigned",
                    "assignment_group": assignment_group,
                    "sme_contact": sme_contact,
                    "parent_incident": None,
                    "short_description": short_desc,
                    "work_notes": work_notes,
                    "description": description,
                    "category": category,
                    "subcategory": subcategory,
                    "runbook_id": runbook_id,
                    "impact": "1",
                    "urgency": "1",
                    "created_at": now_ts,
                }

                # Persist to DB and Outbox
                self._persist_and_outbox(inc_record)
                created_incidents.append(inc_record)
                self.logger.info(f"Generated P1 Incident [{inc_num}] for FAILED job [{job_id}] -> {assignment_group}")

            # ------------------------------------------------------------------
            # Rule B: Cascading Block -> Correlated Child Ticket (No P1 Flood)
            # ------------------------------------------------------------------
            elif status == "BLOCKED_BY_UPSTREAM":
                inc_num = database.get_next_incident_number(self.db_path)

                # Determine parent incident by checking upstream dependency
                parent_inc = None
                # If stderr mentions upstream job, extract it
                for failed_jid, p_num in parent_incident_map.items():
                    if failed_jid in stderr_log or failed_jid in job.get("job_id", ""):
                        parent_inc = p_num
                        break
                # Fallback to the first failed job incident if only one failed
                if not parent_inc and parent_incident_map:
                    parent_inc = list(parent_incident_map.values())[0]

                short_desc = (
                    f"[CASCADE SUPPRESSION] Execution Blocked: {job_name} ({job_id}) "
                    f"- Awaiting Parent {parent_inc or 'Upstream'}"
                )

                work_notes = (
                    f"--- INCIDENT AUTO-GENERATED BY FINOPS-BATCHGUARD ---\n"
                    f"Run ID: {run_id}\n"
                    f"Job: {job_id} ({job_name})\n"
                    f"Trigger: Upstream dependency failure. Execution safely halted.\n"
                    f"Linked Parent Incident: {parent_inc or 'N/A'}\n"
                    f"ITIL Rule Applied: Automated Alert Suppression. Priority demoted to P3 - Moderate.\n"
                    f"State: On Hold - Awaiting Upstream.\n"
                    f"Assigned Group: {assignment_group} (FYI only until upstream resolves)."
                )

                description = (
                    f"Job '{job_id}' was automatically bypassed and marked BLOCKED_BY_UPSTREAM "
                    f"to prevent corrupt ledger processing. Correlated as child incident to {parent_inc}."
                )

                inc_record = {
                    "incident_number": inc_num,
                    "run_id": run_id,
                    "job_id": job_id,
                    "incident_type": "UPSTREAM_DEPENDENCY_BLOCK",
                    "priority": "P3 - Moderate",
                    "state": "On Hold - Awaiting Upstream",
                    "assignment_group": assignment_group,
                    "sme_contact": sme_contact,
                    "parent_incident": parent_inc,
                    "short_description": short_desc,
                    "work_notes": work_notes,
                    "description": description,
                    "category": category,
                    "subcategory": subcategory,
                    "runbook_id": runbook_id,
                    "impact": "3",
                    "urgency": "3",
                    "created_at": now_ts,
                }

                self._persist_and_outbox(inc_record)
                created_incidents.append(inc_record)
                self.logger.info(
                    f"Generated Child Incident [{inc_num}] for BLOCKED job [{job_id}] "
                    f"(Parent: {parent_inc}) -> {assignment_group}"
                )

            # ------------------------------------------------------------------
            # Rule C: Recovered Job with SLA Breach -> P2 SLA Warning Ticket
            # ------------------------------------------------------------------
            elif status == "SUCCESS" and sla_breached:
                inc_num = database.get_next_incident_number(self.db_path)

                short_desc = (
                    f"[SLA BREACH WARNING] {job_name} ({job_id}) recovered on Retry "
                    f"but breached SLA ({duration_sec:.2f}s)"
                )

                work_notes = (
                    f"--- INCIDENT AUTO-GENERATED BY FINOPS-BATCHGUARD ---\n"
                    f"Run ID: {run_id}\n"
                    f"Job: {job_id} ({job_name})\n"
                    f"Execution Status: SUCCESS on attempt #{attempt_count} (Auto-Retry Succeeded).\n"
                    f"Total Elapsed Wall-Clock: {duration_sec:.2f}s (SLA Limit: 1.5s).\n"
                    f"Root Cause: Transient database lock contention caused retry backoff delay.\n"
                    f"ACTION REQUIRED: Non-outage investigation ticket for {assignment_group} "
                    f"to review table lock contention.\n"
                    f"Standard Operating Procedure: {runbook_id}"
                )

                description = (
                    f"Batch job '{job_id}' completed successfully after auto-retry, "
                    f"but accumulated {duration_sec:.2f}s total duration exceeding its 1.5s SLA window.\n"
                    f"Review database lock contention logs to prevent future upstream delivery delays."
                )

                inc_record = {
                    "incident_number": inc_num,
                    "run_id": run_id,
                    "job_id": job_id,
                    "incident_type": "SLA_BREACH_WARNING",
                    "priority": "P2 - High",
                    "state": "New",
                    "assignment_group": assignment_group,
                    "sme_contact": sme_contact,
                    "parent_incident": None,
                    "short_description": short_desc,
                    "work_notes": work_notes,
                    "description": description,
                    "category": category,
                    "subcategory": subcategory,
                    "runbook_id": runbook_id,
                    "impact": "2",
                    "urgency": "2",
                    "created_at": now_ts,
                }

                self._persist_and_outbox(inc_record)
                created_incidents.append(inc_record)
                self.logger.info(
                    f"Generated P2 SLA Warning [{inc_num}] for recovered job [{job_id}] "
                    f"({duration_sec:.2f}s) -> {assignment_group}"
                )

        return created_incidents

    def _persist_and_outbox(self, inc: Dict[str, Any]) -> None:
        """
        Saves incident to SQLite and exports ServiceNow Table API REST payload to JSON outbox.
        """
        database.insert_incident(
            incident_number=inc["incident_number"],
            run_id=inc["run_id"],
            job_id=inc["job_id"],
            incident_type=inc["incident_type"],
            priority=inc["priority"],
            state=inc["state"],
            assignment_group=inc["assignment_group"],
            sme_contact=inc["sme_contact"],
            parent_incident=inc["parent_incident"],
            short_description=inc["short_description"],
            work_notes=inc["work_notes"],
            created_at=inc["created_at"],
            db_path=self.db_path,
        )

        # Build ServiceNow Table API format: POST /api/now/table/incident
        servicenow_payload = {
            "number": inc["incident_number"],
            "caller_id": self.matrix_config.get("default_caller_id", "batchguard.automation"),
            "category": inc.get("category", "Batch Automation"),
            "subcategory": inc.get("subcategory", "Core Banking"),
            "contact_type": "Automated Event",
            "impact": inc.get("impact", "3"),
            "urgency": inc.get("urgency", "3"),
            "priority": inc["priority"],
            "state": inc["state"],
            "assignment_group": inc["assignment_group"],
            "assigned_to": inc["sme_contact"],
            "short_description": inc["short_description"],
            "description": inc.get("description", inc["short_description"]),
            "u_kb_article": inc.get("runbook_id", "KB0010001"),
            "parent_incident": inc["parent_incident"],
            "work_notes": inc["work_notes"],
            "u_batch_run_id": inc["run_id"],
            "u_job_id": inc["job_id"],
            "u_incident_type": inc["incident_type"],
            "sys_created_on": inc["created_at"],
        }

        outbox_file = self.outbox_dir / f"{inc['incident_number']}.json"
        with open(outbox_file, "w", encoding="utf-8") as f:
            json.dump(servicenow_payload, f, indent=2)

