"""
Database layer for FinOps-BatchGuard.
Manages SQLite operations for batch schedules, job run states, audit logs, SLA metrics,
and ServiceNow Incident tickets.
"""

import sqlite3
from pathlib import Path
from typing import Any, Dict, List, Optional
from datetime import datetime

DEFAULT_DB_PATH = Path(__file__).resolve().parent.parent / "data" / "batch_ops.db"


def get_db_path(custom_path: Optional[str] = None) -> Path:
    if custom_path:
        return Path(custom_path)
    return DEFAULT_DB_PATH


def get_connection(db_path: Optional[Path] = None) -> sqlite3.Connection:
    target_path = db_path or DEFAULT_DB_PATH
    target_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(target_path))
    conn.row_factory = sqlite3.Row
    # Enable foreign keys and WAL mode for better concurrency and durability
    conn.execute("PRAGMA foreign_keys = ON;")
    conn.execute("PRAGMA journal_mode = WAL;")
    return conn


def init_db(db_path: Optional[Path] = None) -> None:
    """
    Initializes database tables and indexes.
    Tables:
      - job_runs: Authoritative state of each job for a batch run.
      - job_run_attempts: Granular execution attempt history (including retries).
      - incidents: ServiceNow Incident tickets generated by ITIL triage engine.
    """
    conn = get_connection(db_path)
    try:
        with conn:
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS job_runs (
                    run_id TEXT NOT NULL,
                    batch_date TEXT NOT NULL,
                    job_id TEXT NOT NULL,
                    job_name TEXT NOT NULL,
                    status TEXT NOT NULL CHECK(status IN ('RUNNING', 'SUCCESS', 'RETRYING', 'FAILED', 'BLOCKED_BY_UPSTREAM')),
                    attempt_count INTEGER NOT NULL DEFAULT 0,
                    exit_code INTEGER,
                    start_time TEXT,
                    end_time TEXT,
                    duration_sec REAL DEFAULT 0.0,
                    sla_breached INTEGER NOT NULL DEFAULT 0 CHECK(sla_breached IN (0, 1)),
                    stdout_log TEXT,
                    stderr_log TEXT,
                    PRIMARY KEY (run_id, job_id)
                );
                """
            )

            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS job_run_attempts (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    run_id TEXT NOT NULL,
                    batch_date TEXT NOT NULL,
                    job_id TEXT NOT NULL,
                    job_name TEXT NOT NULL,
                    attempt_number INTEGER NOT NULL,
                    status TEXT NOT NULL,
                    exit_code INTEGER,
                    start_time TEXT,
                    end_time TEXT,
                    duration_sec REAL DEFAULT 0.0,
                    stdout_log TEXT,
                    stderr_log TEXT,
                    FOREIGN KEY (run_id, job_id) REFERENCES job_runs(run_id, job_id) ON DELETE CASCADE
                );
                """
            )

            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS incidents (
                    incident_number TEXT PRIMARY KEY,
                    run_id TEXT NOT NULL,
                    job_id TEXT NOT NULL,
                    incident_type TEXT NOT NULL CHECK(incident_type IN ('HARD_FAILURE', 'SLA_BREACH_WARNING', 'UPSTREAM_DEPENDENCY_BLOCK')),
                    priority TEXT NOT NULL CHECK(priority IN ('P1 - Critical', 'P2 - High', 'P3 - Moderate')),
                    state TEXT NOT NULL CHECK(state IN ('New', 'Assigned', 'On Hold - Awaiting Upstream')),
                    assignment_group TEXT NOT NULL,
                    sme_contact TEXT NOT NULL,
                    parent_incident TEXT,
                    short_description TEXT NOT NULL,
                    work_notes TEXT,
                    created_at TEXT NOT NULL,
                    FOREIGN KEY (run_id, job_id) REFERENCES job_runs(run_id, job_id) ON DELETE CASCADE
                );
                """
            )

            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS housekeeping_checks (
                    check_id INTEGER PRIMARY KEY AUTOINCREMENT,
                    run_id TEXT NOT NULL,
                    check_category TEXT NOT NULL,
                    metric_name TEXT NOT NULL,
                    measured_value TEXT NOT NULL,
                    threshold TEXT NOT NULL,
                    compliance_status TEXT NOT NULL CHECK(compliance_status IN ('COMPLIANT', 'WARNING', 'CRITICAL')),
                    checked_at TEXT NOT NULL
                );
                """
            )

            # Performance indexes
            conn.execute("CREATE INDEX IF NOT EXISTS idx_job_runs_run_id ON job_runs(run_id);")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_job_runs_status ON job_runs(status);")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_job_attempts_run_job ON job_run_attempts(run_id, job_id);")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_incidents_run_id ON incidents(run_id);")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_incidents_job_id ON incidents(job_id);")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_housekeeping_run_id ON housekeeping_checks(run_id);")
    finally:
        conn.close()


def upsert_job_run(
    run_id: str,
    batch_date: str,
    job_id: str,
    job_name: str,
    status: str,
    attempt_count: int,
    exit_code: Optional[int] = None,
    start_time: Optional[str] = None,
    end_time: Optional[str] = None,
    duration_sec: float = 0.0,
    sla_breached: int = 0,
    stdout_log: Optional[str] = None,
    stderr_log: Optional[str] = None,
    db_path: Optional[Path] = None,
) -> None:
    """
    Inserts or updates the current state of a job run in the job_runs table.
    """
    conn = get_connection(db_path)
    try:
        with conn:
            conn.execute(
                """
                INSERT INTO job_runs (
                    run_id, batch_date, job_id, job_name, status,
                    attempt_count, exit_code, start_time, end_time,
                    duration_sec, sla_breached, stdout_log, stderr_log
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(run_id, job_id) DO UPDATE SET
                    status = excluded.status,
                    attempt_count = excluded.attempt_count,
                    exit_code = excluded.exit_code,
                    start_time = COALESCE(excluded.start_time, job_runs.start_time),
                    end_time = excluded.end_time,
                    duration_sec = excluded.duration_sec,
                    sla_breached = excluded.sla_breached,
                    stdout_log = excluded.stdout_log,
                    stderr_log = excluded.stderr_log;
                """,
                (
                    run_id,
                    batch_date,
                    job_id,
                    job_name,
                    status,
                    attempt_count,
                    exit_code,
                    start_time,
                    end_time,
                    duration_sec,
                    1 if sla_breached else 0,
                    stdout_log or "",
                    stderr_log or "",
                ),
            )
    finally:
        conn.close()


