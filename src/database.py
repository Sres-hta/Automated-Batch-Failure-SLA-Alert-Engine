def get_job_runs(run_id: Optional[str] = None, db_path: Optional[Path] = None) -> List[Dict[str, Any]]:
    """
    Retrieves job runs for a specific batch run or all runs.
    """
    conn = get_connection(db_path)
    try:
        cursor = conn.cursor()
        if run_id:
            cursor.execute(
                "SELECT * FROM job_runs WHERE run_id = ? ORDER BY rowid ASC;",
                (run_id,),
            )
        else:
            cursor.execute("SELECT * FROM job_runs ORDER BY rowid ASC;")
        rows = cursor.fetchall()
        return [dict(row) for row in rows]
    finally:
        conn.close()


def get_job_run_attempts(
    run_id: Optional[str] = None,
    job_id: Optional[str] = None,
    db_path: Optional[Path] = None,
) -> List[Dict[str, Any]]:
    """
    Retrieves individual execution attempts.
    """
    conn = get_connection(db_path)
    try:
        cursor = conn.cursor()
        query = "SELECT * FROM job_run_attempts WHERE 1=1"
        params: List[Any] = []
        if run_id:
            query += " AND run_id = ?"
            params.append(run_id)
        if job_id:
            query += " AND job_id = ?"
            params.append(job_id)
        query += " ORDER BY id ASC;"
        cursor.execute(query, params)
        rows = cursor.fetchall()
        return [dict(row) for row in rows]
    finally:
        conn.close()


def get_next_incident_number(db_path: Optional[Path] = None) -> str:
    """
    Generates the next sequential ServiceNow Incident number, starting from INC0010401.
    """
    conn = get_connection(db_path)
    try:
        cursor = conn.cursor()
        cursor.execute(
            """
            SELECT MAX(CAST(SUBSTR(incident_number, 4) AS INTEGER))
            FROM incidents
            WHERE incident_number LIKE 'INC%';
            """
        )
        row = cursor.fetchone()
        max_num = row[0] if (row and row[0] is not None) else 10400
        next_num = max_num + 1
        return f"INC{next_num:07d}"
    finally:
        conn.close()


def insert_incident(
    incident_number: str,
    run_id: str,
    job_id: str,
    incident_type: str,
    priority: str,
    state: str,
    assignment_group: str,
    sme_contact: str,
    parent_incident: Optional[str],
    short_description: str,
    work_notes: str,
    created_at: Optional[str] = None,
    db_path: Optional[Path] = None,
) -> None:
    """
    Persists a newly created ServiceNow incident into the incidents table.
    """
    conn = get_connection(db_path)
    ts = created_at or datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    try:
        with conn:
            conn.execute(
                """
                INSERT INTO incidents (
                    incident_number, run_id, job_id, incident_type, priority,
                    state, assignment_group, sme_contact, parent_incident,
                    short_description, work_notes, created_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(incident_number) DO UPDATE SET
                    state = excluded.state,
                    assignment_group = excluded.assignment_group,
                    sme_contact = excluded.sme_contact,
                    parent_incident = excluded.parent_incident,
                    short_description = excluded.short_description,
                    work_notes = excluded.work_notes;
                """,
                (
                    incident_number,
                    run_id,
                    job_id,
                    incident_type,
                    priority,
                    state,
                    assignment_group,
                    sme_contact,
                    parent_incident,
                    short_description,
                    work_notes,
                    ts,
                ),
            )
    finally:
        conn.close()


